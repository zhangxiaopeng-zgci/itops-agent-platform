function preserveWhitespace(original: string, translated: string): string {
  const prefix = original.match(/^\s*/)?.[0] || '';
  const suffix = original.match(/\s*$/)?.[0] || '';
  return `${prefix}${translated}${suffix}`;
}

export function hasChineseText(value: string): boolean {
  return /[\u4e00-\u9fff]/.test(value);
}

export function translateZhText(value: string): string {
  if (!hasChineseText(value)) return value;

  const trimmed = value.trim();
  if (!trimmed) return value;

  const exact = EXACT_TRANSLATIONS[trimmed] || ADDITIONAL_EXACT_TRANSLATIONS[trimmed];
  if (exact) return preserveWhitespace(value, exact);

  for (const [pattern, handler] of DYNAMIC_TRANSLATIONS) {
    const match = trimmed.match(pattern);
    if (match) return preserveWhitespace(value, handler(match));
  }

  let translated = trimmed;
  const phrases = Object.entries({ ...PHRASE_TRANSLATIONS, ...EXACT_TRANSLATIONS, ...ADDITIONAL_EXACT_TRANSLATIONS })
    .sort((a, b) => b[0].length - a[0].length);

  for (const [source, target] of phrases) {
    translated = translated.split(source).join(target);
  }

  return preserveWhitespace(value, translated);
}
